# Domain separation tags to prevent cross-protocol collision attacks
HOP1_DOMAIN_TAG: bytes = b"PPA-IOT-HOP1-SENSOR-V1"
HOP2_DOMAIN_TAG: bytes = b"PPA-IOT-HOP2-AGGREGATOR-V1"


def build_bitmask(reporting_sensor_ids: Sequence[str], sensor_universe: Sequence[str]) -> bytes:
    """
    Constructs a compact binary bitmask indicating which sensors in the universe reported.

    Format:
        For a universe of U sensors, the bitmask has ceil(U / 8) bytes.
        Sensor at index i in sensor_universe sets bit (i % 8) in byte (i // 8) to 1.

    Args:
        reporting_sensor_ids: IDs of sensors that successfully reported.
        sensor_universe: Ordered canonical list of all enrolled sensor IDs.

    Returns:
        bytes representing the bitmask.

    Raises:
        ValueError: If an unknown sensor ID appears or universe is empty.
    """
    if not sensor_universe:
        raise ValueError("Sensor universe cannot be empty")

    universe_map = {sid: idx for idx, sid in enumerate(sensor_universe)}
    total_sensors = len(sensor_universe)
    n_bytes = math.ceil(total_sensors / 8)
    mask = bytearray(n_bytes)

    for sid in reporting_sensor_ids:
        if sid not in universe_map:
            raise ValueError(f"Unknown sensor ID '{sid}' not in sensor universe")
        idx = universe_map[sid]
        byte_idx = idx // 8
        bit_idx = idx % 8
        mask[byte_idx] |= (1 << bit_idx)

    return bytes(mask)


def count_bitmask_sensors(bitmask: bytes) -> int:
    """Computes the Hamming weight (number of set bits) in a bitmask."""
    count = 0
    for byte in bitmask:
        count += bin(byte).count("1")
    return count


def decode_bitmask_sensors(bitmask: bytes, sensor_universe: Sequence[str]) -> List[str]:
    """
    Recovers the list of reporting sensor IDs from a bitmask and universe.

    Args:
        bitmask: Binary bitmask bytes.
        sensor_universe: Canonical ordered universe of sensor IDs.

    Returns:
        List of sensor IDs corresponding to 1 bits.
    """
    expected_bytes = math.ceil(len(sensor_universe) / 8)
    if len(bitmask) != expected_bytes:
        raise ValueError(
            f"Bitmask length mismatch: expected {expected_bytes} bytes for {len(sensor_universe)} sensors, got {len(bitmask)}"
        )

    reporting = []
    for idx, sid in enumerate(sensor_universe):
        byte_idx = idx // 8
        bit_idx = idx % 8
        if (bitmask[byte_idx] >> bit_idx) & 1:
            reporting.append(sid)
    return reporting


# ---------------------------------------------------------------------------
# Hop-1: Sensor -> Aggregator
# ---------------------------------------------------------------------------

def serialize_hop1_payload(sensor_id: str, c1: Point, c2: Point, seq: int, epoch: int) -> bytes:
    """
    Deterministically serializes the Hop-1 payload for HMAC computation.

    Canonical Format:
        HOP1_DOMAIN_TAG (23 bytes)
        || len(sensor_id) (2 bytes uint16 big-endian)
        || sensor_id (UTF-8 bytes)
        || C1 (65 bytes SEC1)
        || C2 (65 bytes SEC1)
        || Seq (8 bytes uint64 big-endian)
        || Epoch (8 bytes uint64 big-endian)

    Binding Sensor Identity:
        Binding `sensor_id` directly into the authenticated payload guarantees that
        a MAC generated by Sensor A cannot be presented as having originated from Sensor B,
        even if an attacker attempts identity spoofing at the transport layer.
    """
    id_bytes = sensor_id.encode("utf-8")
    if len(id_bytes) > 65535:
        raise ValueError("Sensor ID exceeds maximum 16-bit length prefix")

    c1_bytes = point_to_bytes(c1)
    c2_bytes = point_to_bytes(c2)
    seq_bytes = seq.to_bytes(8, byteorder="big")
    epoch_bytes = epoch.to_bytes(8, byteorder="big")
    len_id_bytes = len(id_bytes).to_bytes(2, byteorder="big")

    return (
        HOP1_DOMAIN_TAG
        + len_id_bytes
        + id_bytes
        + c1_bytes
        + c2_bytes
        + seq_bytes
        + epoch_bytes
    )


def compute_hop1_mac(sensor_key: bytes, sensor_id: str, c1: Point, c2: Point, seq: int, epoch: int) -> bytes:
    """
    Computes an HMAC-SHA256 authentication tag for a Hop-1 sensor packet.

    Args:
        sensor_key: 32-byte secret symmetric authentication key unique to this sensor.
        sensor_id: Identifier of the sensor.
        c1: Lifted ElGamal C1 point.
        c2: Lifted ElGamal C2 point.
        seq: Monotonically increasing sequence number.
        epoch: Time epoch identifier.

    Returns:
        32-byte HMAC-SHA256 digest.
    """
    if len(sensor_key) < 16:
        raise ValueError("Sensor authentication key must be at least 16 bytes")
    payload = serialize_hop1_payload(sensor_id, c1, c2, seq, epoch)
    return hmac.new(sensor_key, payload, hashlib.sha256).digest()


def verify_hop1_mac(
    sensor_key: bytes,
    sensor_id: str,
    c1: Point,
    c2: Point,
    seq: int,
    epoch: int,
    mac: bytes,
) -> bool:
    """
    Verifies a Hop-1 HMAC tag in constant time using hmac.compare_digest().

    Constant-Time Comparison:
        Using `hmac.compare_digest()` prevents timing side-channel attacks where an attacker
        measures microsecond differences in comparison termination to guess bytes of the MAC tag.
    """
    if not isinstance(mac, (bytes, bytearray)) or len(mac) != 32:
        return False
    expected = compute_hop1_mac(sensor_key, sensor_id, c1, c2, seq, epoch)
    return hmac.compare_digest(expected, mac)


@dataclass(frozen=True)
class SensorPacket:
    """Represents an authenticated telemetry packet from a sensor to the aggregator."""
    sensor_id: str
    c1: Point
    c2: Point
    seq: int
    epoch: int
    mac: bytes

    def ciphertext(self) -> Ciphertext:
        return Ciphertext(c1=self.c1, c2=self.c2)


# ---------------------------------------------------------------------------
# Hop-2: Aggregator -> Decryptor
# ---------------------------------------------------------------------------

def serialize_hop2_payload(
    c1_agg: Point,
    c2_agg: Point,
    n_count: int,
    epoch: int,
    bitmask: bytes,
) -> bytes:
    """
    Deterministically serializes the Hop-2 payload for HMAC computation.

    Canonical Format:
        HOP2_DOMAIN_TAG (27 bytes)
        || C1_agg (65 bytes SEC1)
        || C2_agg (65 bytes SEC1)
        || N_count (4 bytes uint32 big-endian)
        || Epoch (8 bytes uint64 big-endian)
        || len(bitmask) (2 bytes uint16 big-endian)
        || bitmask (raw bytes)

    Why Every Metadata Field is Authenticated:
        If the Decryptor accepts an unauthenticated N_count or bitmask, an adversary could
        modify N without modifying the ciphertext, causing the Decryptor to compute the wrong
        interval shift: P_shifted = P - (100 * N) * G.
        Authenticating N, Epoch, and Bitmask protects against metadata forgery.
    """
    c1_bytes = point_to_bytes(c1_agg)
    c2_bytes = point_to_bytes(c2_agg)
    n_bytes = n_count.to_bytes(4, byteorder="big")
    epoch_bytes = epoch.to_bytes(8, byteorder="big")
    len_bitmask = len(bitmask).to_bytes(2, byteorder="big")

    return (
        HOP2_DOMAIN_TAG
        + c1_bytes
        + c2_bytes
        + n_bytes
        + epoch_bytes
        + len_bitmask
        + bitmask
    )


def compute_hop2_mac(
    decryptor_key: bytes,
    c1_agg: Point,
    c2_agg: Point,
    n_count: int,
    epoch: int,
    bitmask: bytes,
) -> bytes:
    """
    Computes an HMAC-SHA256 authentication tag for a Hop-2 aggregate packet.

    Args:
        decryptor_key: 32-byte secret symmetric key shared between Aggregator and Decryptor.
        c1_agg: Aggregated C1 point.
        c2_agg: Aggregated C2 point.
        n_count: Count of aggregated sensors.
        epoch: Time epoch identifier.
        bitmask: Binary participation bitmask.

    Returns:
        32-byte HMAC-SHA256 digest.
    """
    if len(decryptor_key) < 16:
        raise ValueError("Decryptor authentication key must be at least 16 bytes")
    payload = serialize_hop2_payload(c1_agg, c2_agg, n_count, epoch, bitmask)
    return hmac.new(decryptor_key, payload, hashlib.sha256).digest()


def verify_hop2_mac(
    decryptor_key: bytes,
    c1_agg: Point,
    c2_agg: Point,
    n_count: int,
    epoch: int,
    bitmask: bytes,
    mac: bytes,
) -> bool:
    """Verifies a Hop-2 HMAC tag in constant time using hmac.compare_digest()."""
    if not isinstance(mac, (bytes, bytearray)) or len(mac) != 32:
        return False
    expected = compute_hop2_mac(decryptor_key, c1_agg, c2_agg, n_count, epoch, bitmask)
    return hmac.compare_digest(expected, mac)


@dataclass(frozen=True)
class AggregatePacket:
    """Represents an authenticated aggregated packet from the aggregator to the decryptor."""
    c1_agg: Point
    c2_agg: Point
    count: int
    epoch: int
    bitmask: bytes
    mac: bytes

    def ciphertext(self) -> Ciphertext:
        return Ciphertext(c1=self.c1_agg, c2=self.c2_agg)
