"""
Two-hop authentication architecture for IoT privacy-preserving aggregation.
Implements HMAC-SHA256 authentication for Hop-1 (Sensor->Aggregator)
and Hop-2 (Aggregator->Decryptor) with replay protection and metadata validation.
"""

